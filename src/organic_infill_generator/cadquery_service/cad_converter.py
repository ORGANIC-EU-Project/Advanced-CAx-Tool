from __future__ import annotations

import logging
from pathlib import Path

import cadquery as cq
from OCP.BRepBuilderAPI import BRepBuilderAPI_Sewing
from OCP.STEPControl import STEPControl_ShellBasedSurfaceModel, STEPControl_Writer
from OCP.StlAPI import StlAPI_Reader
from OCP.TopoDS import TopoDS_Shape

from .helpers import ensure_nonempty, ensure_parent, file_size_bytes, now
from .settings import StepToStlSettings, StlToStepSettings

logger = logging.getLogger(__name__)


def step_to_stl(step_path: Path, stl_path: Path) -> dict:
    """Import a STEP as a parametric solid with CadQuery and export it to STL."""
    ensure_parent(stl_path)

    timings = {}
    t_start = now()

    shape = cq.importers.importStep(str(step_path))
    if shape is None:
        raise RuntimeError(f"CadQuery failed to import STEP: {step_path}")

    linear_defl = StepToStlSettings.LINEAR_DEFLECTION
    angular_defl = StepToStlSettings.ANGULAR_DEFLECTION

    if StepToStlSettings.AUTO_TOLERANCE:
        bb = shape.val().BoundingBox()
        linear_defl = bb.DiagonalLength * StepToStlSettings.RELATIVE_LINEAR_DEFLECTION
        angular_defl = StepToStlSettings.AUTO_ANGULAR_DEFLECTION
        logger.info("Auto tolerance: diagonal %.2f, linear %.4f, angular %.4f",
                    bb.DiagonalLength, linear_defl, angular_defl)

    cq.exporters.export(
        shape,
        str(stl_path),
        tolerance=linear_defl,
        angularTolerance=angular_defl,
        opt={"ascii": False},
    )

    ensure_nonempty(stl_path, "STL generated by CadQuery")
    timings["step_to_stl_seconds"] = now() - t_start

    return {
        "operation": "STEP -> STL",
        "backend": "cadquery",
        "input": str(step_path),
        "output": str(stl_path),
        "sizes_bytes": {
            "input_step": file_size_bytes(step_path),
            "output_stl": file_size_bytes(stl_path),
        },
        "timings": timings,
    }


def stl_to_step(stl_path: Path, step_path: Path) -> dict:
    """Read an STL with OCP, sew triangle faces, and export STEP."""
    ensure_parent(step_path)

    timings = {}
    t_start = now()

    reader = StlAPI_Reader()
    shape = TopoDS_Shape()
    if not reader.Read(shape, str(stl_path)):
        raise RuntimeError(f"OCP failed to read the STL: {stl_path}")

    sewer = BRepBuilderAPI_Sewing(StlToStepSettings.SEW_TOLERANCE)
    sewer.Add(shape)
    sewer.Perform()

    sewn_shape = sewer.SewedShape()
    if not sewn_shape.IsNull():
        shape = sewn_shape
    timings["sew_seconds"] = now() - t_start

    t_write = now()
    writer = STEPControl_Writer()
    status = writer.Transfer(shape, STEPControl_ShellBasedSurfaceModel)
    if int(status) in (2, 3):
        raise RuntimeError(f"OCP STL -> STEP transfer failed: {stl_path}")

    write_status = writer.Write(str(step_path))
    if int(write_status) not in (0, 1):
        raise RuntimeError(f"Failed to write STEP: {step_path}")

    ensure_nonempty(step_path, "STEP generated by OCP")
    timings["write_step_seconds"] = now() - t_write
    timings["stl_to_step_seconds"] = now() - t_start

    return {
        "operation": "STL -> STEP",
        "backend": "OCP",
        "input": str(stl_path),
        "output": str(step_path),
        "sizes_bytes": {
            "input_stl": file_size_bytes(stl_path),
            "output_step": file_size_bytes(step_path),
        },
        "timings": timings,
    }
